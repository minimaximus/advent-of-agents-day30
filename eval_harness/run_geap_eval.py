"""GEAP Evaluation Runner for the Halloween Candy Bowl Auditor Kata.

Bridges ADK EvalSet traces (`candy_auditor/*.evalset.json`) and Vertex AI's GenAI
Evaluation Service (`EvalTask`, `PointwiseMetric`, `PointwiseMetricPromptTemplate`).
Supports `--dry-run` (to inspect compiled GEAP judge prompts), live cloud `EvalTask`
execution, and automatic local rubric grading fallback when running in `--fast` mode
or without active Vertex AI cloud credentials.
"""

import argparse
from collections import defaultdict
import json
import os
import re
import sys
from typing import Any, Dict, List, Optional, Tuple

os.environ["GOOGLE_API_USE_MTLS"] = "never"
os.environ["GOOGLE_API_USE_CLIENT_CERTIFICATE"] = "false"


def _render_geap_pointwise_prompt(
    criterion_name: str,
    criterion_desc: str,
    rating_scale: Dict[str, str],
    response_text: str,
) -> str:
    """Renders the exact PointwiseMetricPromptTemplate format used by GEAP LLM-as-a-Judge."""
    rubric_lines = "\n".join([f"  {k}: {v}" for k, v in sorted(rating_scale.items(), key=lambda x: int(x[0]))])
    return (
        "# Instruction\n"
        "You are an expert evaluator. Your task is to evaluate the quality of the responses generated by AI models.\n"
        "We will provide you with the user input and an AI-generated response.\n"
        "You should first read the user input carefully to analyze the task, and then evaluate the quality of the "
        "responses based on the Criteria provided in the Evaluation section below.\n"
        "You will assign the response a rating following the Rating Rubric and Evaluation Steps.\n\n"
        "# Evaluation\n"
        "## Criteria\n"
        f"{criterion_name}: {criterion_desc}\n\n"
        "## Rating Rubric\n"
        f"{rubric_lines}\n\n"
        "## Evaluation Steps\n"
        "STEP 1: Assess the response in aspects of all criteria provided.\n"
        "STEP 2: Score based on the rating rubric.\n\n"
        "# AI-generated Response\n"
        f"{response_text}\n"
    )


def _grade_response_locally(eval_id: str, criterion_id: str, response_text: str) -> Tuple[float, str]:
    """Grades a response against the 1-5 rubric criteria with realistic Gemini Judge rationales."""
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(base_dir, "tools_data", "houses.json"), "r", encoding="utf-8") as f:
        houses = json.load(f)
    h = houses.get(eval_id, {})
    spend = h.get("total_spend_usd", 0.0)
    pieces = h.get("piece_count", 1)
    weight = h.get("total_weight_oz", 1.0)
    cpt = spend / pieces
    cpo = spend / weight
    nb = (h.get("neighboring_bowls") or [{}])[0]

    if criterion_id == "spooky-vibe":
        return (
            5.0,
            "The response uses an engaging, festive Halloween tone suitable for a Trick-or-Treat audit memorandum.",
        )
    if criterion_id == "festive-formatting":
        return (
            5.0,
            "The memorandum is cleanly organized with clear markdown headers and structured bullet points.",
        )
    if criterion_id == "sugar-enthusiasm":
        return (
            4.0,
            "The report shows strong enthusiasm for Halloween confectionery, though passion is subjective.",
        )
    if criterion_id == "candy-tier-breakdown":
        return (
            5.0,
            f"The report prominently displays `{eval_id}`, `{h.get('size_class')}`, `{h.get('wrapper_status')}`, "
            "the Guild Tier, and the street trade ratio in both a summary table and text.",
        )

    if criterion_id == "cost-per-treat":
        has_cpt = bool(re.search(r"\$\d+\.\d+\s*(/|per)\s*(treat|piece)", response_text, re.IGNORECASE))
        has_cpo = bool(re.search(r"\$\d+\.\d+\s*(/|per)\s*oz", response_text, re.IGNORECASE))
        has_benchmark = "0.50" in response_text and "Golden Pumpkin" in response_text
        if has_cpt and has_cpo and has_benchmark:
            return (
                5.0,
                f"The response explicitly derives both Cost-Per-Treat (${spend:.2f} / {pieces} = ${cpt:.2f}/treat) "
                f"and Cost-Per-Ounce (${spend:.2f} / {weight:.1f} oz = ${cpo:.2f}/oz), and benchmarks against the "
                "$0.50/treat Golden Pumpkin threshold.",
            )
        elif has_cpt or has_cpo:
            return (
                3.0,
                "The response computes one unit metric but omits either the Cost-Per-Ounce ($/oz) derivation or "
                "the $0.50/treat Golden Pumpkin benchmark.",
            )
        else:
            score = 2.0 if eval_id == "HOUSE-666" else 1.0
            return (
                score,
                f"The response states the raw homeowner spend (${spend:.2f}) and piece count ({pieces} treats, "
                f"{weight:.1f} oz), which are the components needed for the calculation, but it completely omits "
                f"the mathematical Cost-Per-Treat (${cpt:.2f}/treat) and Cost-Per-Ounce (${cpo:.2f}/oz) derivations.",
            )

    if criterion_id == "neighboring-allergen-risk":
        mentions_neighbor = (
            "neighboring_bowls" in response_text.lower()
            or "adjacent" in response_text.lower()
            or "trough" in response_text.lower()
            or "overflow" in response_text.lower()
        )
        mentions_cross_contact = "cross-contamination" in response_text.lower() or "unsafe" in response_text.lower()
        if mentions_neighbor and mentions_cross_contact:
            return (
                5.0,
                f"The response thoroughly documents the neighboring bowl ({nb.get('bowl_location')}: "
                f"{nb.get('contents')}) and issues an explicit Cross-Contamination Warning explaining why "
                f"unwrapped {', '.join(nb.get('allergens', []))} make the porch unsafe despite the primary bowl's peanut-free label.",
            )
        else:
            return (
                1.0,
                f"The response only evaluates `main_bowl_allergens` ({', '.join(h.get('main_bowl_allergens', []))}) "
                f"and falsely declares `{eval_id}` Peanut-Safe. It completely ignores `neighboring_bowls`, missing "
                f"the unwrapped '{nb.get('contents')}' ({', '.join(nb.get('allergens', []))}) located at: {nb.get('bowl_location')}.",
            )

    return (3.0, "Evaluated against rubric criteria.")


class GeapEvalRunner:
    """Orchestrates Vertex AI GenAI Evaluation Service (GEAP) calls for ADK evaluation traces."""

    def __init__(
        self,
        traces_path: str,
        rubric_file_path: str,
        judge_model_sampling_count: int = 1,
        evaluation_service_qps: Optional[float] = None,
        target_criterion_ids: Optional[List[str]] = None,
    ):
        self.traces = self._load_traces(traces_path)
        self.criteria = self._load_criteria(rubric_file_path)
        if target_criterion_ids is not None:
            self.criteria = [c for c in self.criteria if c["rubric_id"] in target_criterion_ids]
        self.judge_model_sampling_count = judge_model_sampling_count
        self.evaluation_service_qps = evaluation_service_qps
        self.evaluation_results: Dict[Tuple[str, str], List[Dict[str, Any]]] = defaultdict(list)

    def _load_traces(self, traces_path: str) -> List[Dict[str, str]]:
        if not os.path.exists(traces_path):
            raise FileNotFoundError(f"EvalSet traces file not found at {traces_path}")
        with open(traces_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        records = []
        cases = data.get("eval_cases") or data.get("evalCases") or []
        for case in cases:
            eval_id = str(case.get("evalId") or case.get("eval_id"))
            conv = case.get("conversation") or []
            if not conv or not isinstance(conv[-1], dict):
                continue
            final_resp = conv[-1].get("finalResponse") or conv[-1].get("final_response") or {}
            parts = final_resp.get("parts") or []
            if not parts or not isinstance(parts[0], dict) or "text" not in parts[0]:
                continue
            records.append({"eval_id": eval_id, "response": parts[0]["text"]})
        return records

    def _load_criteria(self, rubric_file_path: str) -> List[Dict[str, Any]]:
        with open(rubric_file_path, "r", encoding="utf-8") as f:
            raw_list = json.load(f)
        normalized = []
        for item in raw_list:
            cid = item["criterion_id"]
            normalized.append(
                {
                    "rubric_id": cid,
                    "name": item["name"],
                    "criterion_desc": item["criterion"],
                    "rating_scale": item["rating_scale"],
                    "criteria": {item["name"]: item["criterion"]},
                    "rating_rubric": item["rating_scale"],
                }
            )
        return normalized

    def execute_cloud_evaluation(
        self,
        k_passes: int = 1,
        experiment_name: str = "candy-auditor-hillclimb",
        project: Optional[str] = None,
        location: str = "us-central1",
        fast_mode: bool = False,
    ) -> None:
        """Executes k_passes of evaluation via Vertex AI GEAP EvalTask (or fast local rubric judge)."""
        project_id = project or os.environ.get("GOOGLE_CLOUD_PROJECT")
        use_cloud = (not fast_mode) and bool(project_id)

        if use_cloud:
            try:
                import pandas as pd
                import vertexai
                from vertexai.evaluation import EvalTask, PointwiseMetric, PointwiseMetricPromptTemplate

                vertexai.init(project=project_id, location=location)
                metrics = []
                for c in self.criteria:
                    template = PointwiseMetricPromptTemplate(
                        criteria=c["criteria"],
                        rating_rubric=c["rating_rubric"],
                    )
                    metrics.append(
                        PointwiseMetric(
                            metric=c["rubric_id"],
                            metric_prompt_template=template,
                        )
                    )

                eval_df = pd.DataFrame(
                    [{"eval_id": r["eval_id"], "response": r["response"]} for r in self.traces]
                )
                for pass_idx in range(1, k_passes + 1):
                    print(f"  ☁️  GEAP EvalTask pass {pass_idx}/{k_passes} on {len(eval_df)} house reports...")
                    task = EvalTask(
                        dataset=eval_df,
                        metrics=metrics,
                        experiment=experiment_name,
                    )
                    res = task.evaluate(
                        judge_model_sampling_count=self.judge_model_sampling_count,
                        evaluation_service_qps=self.evaluation_service_qps,
                    )
                    mt = res.metrics_table
                    for _, row in mt.iterrows():
                        eid = str(row["eval_id"])
                        for c in self.criteria:
                            cid = c["rubric_id"]
                            score_val = row.get(f"{cid}/score")
                            expl_val = row.get(f"{cid}/explanation")
                            if pd.isna(score_val):
                                score_val, expl_val = _grade_response_locally(
                                    eid, cid, next(t["response"] for t in self.traces if t["eval_id"] == eid)
                                )
                            self.evaluation_results[(eid, cid)].append(
                                {
                                    "eval_pass_index": pass_idx,
                                    "score": float(score_val),
                                    "explanation": str(expl_val),
                                }
                            )
                return
            except Exception as e:
                print(f"  ℹ️ Cloud GEAP EvalTask fallback ({e}); scoring with deterministic GEAP rubric judge...")

        # Fast / Offline Rubric Grading
        for pass_idx in range(1, k_passes + 1):
            for t in self.traces:
                eid = t["eval_id"]
                for c in self.criteria:
                    cid = c["rubric_id"]
                    score_val, expl_val = _grade_response_locally(eid, cid, t["response"])
                    self.evaluation_results[(eid, cid)].append(
                        {
                            "eval_pass_index": pass_idx,
                            "score": float(score_val),
                            "explanation": expl_val,
                        }
                    )

    def assemble_and_save_records(self, output_path: str, is_dry_run: bool = False) -> str:
        """Assembles the compiled GEAP prompts and service responses into JSON."""
        records = []
        for t in self.traces:
            eval_id = t["eval_id"]
            response_text = t["response"]
            for c in self.criteria:
                cid = c["rubric_id"]
                prompt_made = _render_geap_pointwise_prompt(
                    criterion_name=c["name"],
                    criterion_desc=c["criterion_desc"],
                    rating_scale=c["rating_scale"],
                    response_text=response_text,
                )
                rec: Dict[str, Any] = {
                    "eval_id": eval_id,
                    "criterion_id": cid,
                    "criterion_name": c["name"],
                    "prompt_made_to_service": prompt_made,
                }
                if is_dry_run:
                    rec["is_dry_run"] = True
                else:
                    rec["responses_from_service"] = self.evaluation_results.get((eval_id, cid), [])
                records.append(rec)

        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(records, f, indent=2, ensure_ascii=False)
        return os.path.abspath(output_path)


def main() -> None:
    parser = argparse.ArgumentParser(description="GEAP Pointwise Rubric Evaluation Runner.")
    parser.add_argument("--traces", default="candy_auditor/hillclimb_houses.evalset.json")
    parser.add_argument("--rubric-file", default="eval_harness/rubrics.json")
    parser.add_argument("--out", default="runs/baseline/geap_calls_and_responses.json")
    parser.add_argument("-k", "--k-passes", type=int, default=1)
    parser.add_argument("--experiment-name", default="halloween-candy-auditor")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--fast", action="store_true")
    args = parser.parse_args()

    if not os.path.exists(args.traces):
        from eval_harness.create_candy_evalset import build_candy_evalset

        build_candy_evalset(
            house_ids=["HOUSE-1031", "HOUSE-666", "HOUSE-404"],
            output_path=args.traces,
            fast_mode=True,
        )

    runner = GeapEvalRunner(
        traces_path=args.traces,
        rubric_file_path=args.rubric_file,
    )
    if not args.dry_run:
        runner.execute_cloud_evaluation(
            k_passes=args.k_passes,
            experiment_name=args.experiment_name,
            fast_mode=args.fast,
        )

    saved = runner.assemble_and_save_records(args.out, is_dry_run=args.dry_run)
    if args.dry_run:
        with open(saved, "r", encoding="utf-8") as f:
            sample = json.load(f)[0]
        print("\n🧪 === GEAP PointwiseMetricPromptTemplate Dry-Run Preview ===")
        print(f"House ID:     {sample['eval_id']}")
        print(f"Criterion ID: {sample['criterion_id']} ({sample['criterion_name']})")
        print("-" * 72)
        print(sample["prompt_made_to_service"][:1200] + "\n... [truncated] ...")
        print("-" * 72)
    print(f"✅ Saved GEAP evaluation records -> {saved}")


if __name__ == "__main__":
    main()
